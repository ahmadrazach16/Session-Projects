-- Description:
--   A fully normalized (3NF) relational database supporting an
--   e-commerce platform: users, product catalog, orders, payments,
--   and product reviews.
-- =====================================================================
 

-- =====================================================================
-- SECTION 1: DATABASE CREATION
-- =====================================================================

DROP DATABASE IF EXISTS ecommerce_db;

CREATE DATABASE ecommerce_db
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

USE ecommerce_db;


-- =====================================================================
-- SECTION 2: TABLE CREATION
-- =====================================================================
-- Design notes:
--   - Every table has a single-column surrogate primary key (INT AUTO_INCREMENT)
--     for simplicity and join performance.
--   - Foreign keys enforce referential integrity between related tables.
--   - ON DELETE RESTRICT is used for financial/history tables (Orders,
--     Order_Items, Payments) so historical records can't be silently lost.
--   - ON DELETE CASCADE is used where child rows have no meaning without
--     the parent (e.g. a Review without its User/Product).
--   - The schema is normalized to Third Normal Form (3NF):
--       * Every non-key column depends only on the primary key.
--       * No repeating groups or multi-valued columns.
--       * No transitive dependencies (e.g. product price is stored once
--         in Products and copied into Order_Items only as a historical
--         "price at time of purchase" snapshot, which is standard
--         practice for order-line data, not a normalization violation).
-- =====================================================================

-- ---------------------------------------------------------------------
-- Table: Categories
-- ---------------------------------------------------------------------
CREATE TABLE Categories (
    category_id     INT AUTO_INCREMENT PRIMARY KEY,
    category_name   VARCHAR(100)    NOT NULL UNIQUE,
    description     VARCHAR(255)    DEFAULT NULL
) ENGINE = InnoDB;


-- ---------------------------------------------------------------------
-- Table: Users
-- ---------------------------------------------------------------------
CREATE TABLE Users (
    user_id         INT AUTO_INCREMENT PRIMARY KEY,
    first_name      VARCHAR(50)     NOT NULL,
    last_name       VARCHAR(50)     NOT NULL,
    email           VARCHAR(150)    NOT NULL UNIQUE,
    password_hash   VARCHAR(255)    NOT NULL,
    phone           VARCHAR(20)     DEFAULT NULL,
    address         VARCHAR(255)    DEFAULT NULL,
    city            VARCHAR(100)    DEFAULT NULL,
    country         VARCHAR(100)    DEFAULT NULL,
    created_at      DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE = InnoDB;


-- ---------------------------------------------------------------------
-- Table: Products
-- ---------------------------------------------------------------------
CREATE TABLE Products (
    product_id      INT AUTO_INCREMENT PRIMARY KEY,
    product_name    VARCHAR(150)    NOT NULL,
    category_id     INT             NOT NULL,
    description     VARCHAR(255)    DEFAULT NULL,
    price           DECIMAL(10,2)   NOT NULL,
    stock_quantity  INT             NOT NULL DEFAULT 0,
    created_at      DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_price_non_negative CHECK (price >= 0),
    CONSTRAINT chk_stock_non_negative CHECK (stock_quantity >= 0),
    CONSTRAINT fk_products_category
        FOREIGN KEY (category_id) REFERENCES Categories(category_id)
        ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE = InnoDB;


-- ---------------------------------------------------------------------
-- Table: Orders
-- ---------------------------------------------------------------------
CREATE TABLE Orders (
    order_id        INT AUTO_INCREMENT PRIMARY KEY,
    user_id         INT             NOT NULL,
    order_date      DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status          ENUM('Pending','Processing','Shipped','Delivered','Cancelled')
                                    NOT NULL DEFAULT 'Pending',
    total_amount    DECIMAL(10,2)   NOT NULL DEFAULT 0.00,
    CONSTRAINT fk_orders_user
        FOREIGN KEY (user_id) REFERENCES Users(user_id)
        ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE = InnoDB;


-- ---------------------------------------------------------------------
-- Table: Order_Items
-- ---------------------------------------------------------------------
CREATE TABLE Order_Items (
    order_item_id   INT AUTO_INCREMENT PRIMARY KEY,
    order_id        INT             NOT NULL,
    product_id      INT             NOT NULL,
    quantity        INT             NOT NULL DEFAULT 1,
    unit_price      DECIMAL(10,2)   NOT NULL,
    CONSTRAINT chk_quantity_positive CHECK (quantity > 0),
    CONSTRAINT fk_order_items_order
        FOREIGN KEY (order_id) REFERENCES Orders(order_id)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_order_items_product
        FOREIGN KEY (product_id) REFERENCES Products(product_id)
        ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE = InnoDB;


-- ---------------------------------------------------------------------
-- Table: Payments
-- ---------------------------------------------------------------------
CREATE TABLE Payments (
    payment_id      INT AUTO_INCREMENT PRIMARY KEY,
    order_id        INT             NOT NULL UNIQUE,
    payment_date    DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    payment_method  ENUM('Credit Card','Debit Card','PayPal','Bank Transfer','Cash on Delivery')
                                    NOT NULL,
    amount          DECIMAL(10,2)   NOT NULL,
    payment_status  ENUM('Pending','Completed','Failed','Refunded')
                                    NOT NULL DEFAULT 'Pending',
    CONSTRAINT fk_payments_order
        FOREIGN KEY (order_id) REFERENCES Orders(order_id)
        ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE = InnoDB;


-- ---------------------------------------------------------------------
-- Table: Reviews
-- ---------------------------------------------------------------------
CREATE TABLE Reviews (
    review_id       INT AUTO_INCREMENT PRIMARY KEY,
    product_id      INT             NOT NULL,
    user_id         INT             NOT NULL,
    rating          TINYINT         NOT NULL,
    comment         VARCHAR(500)    DEFAULT NULL,
    review_date     DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_rating_range CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT uq_review_user_product UNIQUE (user_id, product_id),
    CONSTRAINT fk_reviews_product
        FOREIGN KEY (product_id) REFERENCES Products(product_id)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_reviews_user
        FOREIGN KEY (user_id) REFERENCES Users(user_id)
        ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE = InnoDB;


