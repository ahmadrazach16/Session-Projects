-- =====================================================================
-- OPTIMIZATION #2
-- Query: "For each product, show its name and average rating,
--          including products with no reviews yet."
-- =====================================================================

-- ---------------------------------------------------------------------
-- 8.2a SLOW (original) version
-- ---------------------------------------------------------------------
-- Problems:
--   - SELECT * on Products pulls every column even though only name
--     and price are needed.
--   - A correlated subquery runs once PER ROW of Products (200 times),
--     each performing its own scan/aggregation over Reviews — an
--     O(n * m) pattern instead of a single aggregated join.

EXPLAIN ANALYZE
SELECT
    p.*,
    (SELECT AVG(r.rating)
     FROM Reviews r
     WHERE r.product_id = p.product_id) AS average_rating
FROM Products p
ORDER BY p.product_name;

-- ---------------------------------------------------------------------
-- 8.2b OPTIMIZED version
-- ---------------------------------------------------------------------
-- Fixes:
--   - Replaced the correlated subquery with a single LEFT JOIN plus
--     GROUP BY, so Reviews is scanned once and aggregated in one pass
--     instead of once per product.
--   - LEFT JOIN (instead of INNER JOIN) preserves products that have
--     zero reviews, matching the original query's intent.
--   - Replaced SELECT * with only the required columns.
--   - idx_reviews_product (created in Section 7) supports the join
--     condition on Reviews.product_id.

EXPLAIN ANALYZE
SELECT
    p.product_id,
    p.product_name,
    p.price,
    ROUND(AVG(r.rating), 2) AS average_rating,
    COUNT(r.review_id)      AS total_reviews
FROM Products p
LEFT JOIN Reviews r ON r.product_id = p.product_id
GROUP BY p.product_id, p.product_name, p.price
ORDER BY p.product_name;

