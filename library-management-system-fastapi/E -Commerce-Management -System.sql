-- =====================================================================
-- OPTIMIZATION #1
-- Query: "Get full details of all Delivered orders placed in 2025,
--          with customer name and email."
-- =====================================================================

-- ---------------------------------------------------------------------
-- 8.1a SLOW (original) version
-- ---------------------------------------------------------------------
-- Problems:
--   - SELECT * pulls unnecessary columns from both tables, increasing
--     I/O and network payload.
--   - Filtering on YEAR(order_date) applies a function to the indexed
--     column, which prevents MySQL from using idx_orders_date
--     (a "non-sargable" predicate) and forces a full table scan.

EXPLAIN ANALYZE
SELECT *
FROM Orders o
JOIN Users u ON o.user_id = u.user_id
WHERE YEAR(o.order_date) = 2025
  AND o.status = 'Delivered';

-- ---------------------------------------------------------------------
-- 8.1b OPTIMIZED version
-- ---------------------------------------------------------------------
-- Fixes:
--   - Replaced SELECT * with only the required columns.
--   - Replaced YEAR(order_date) = 2025 with a sargable range predicate
--     (order_date >= ... AND order_date < ...), which allows MySQL to
--     use idx_orders_date.
--   - Added a composite index on (status, order_date) since both
--     columns are filtered together; status has low cardinality so it
--     is placed first to narrow the row set before the date range scan.

CREATE INDEX idx_orders_status_date ON Orders(status, order_date);

